
// Aritméticos

/*

+ -> Adição /concatenação

- -> Subtração

/ -> Divisão

* -> Multiplicação

% -> Resto da divisão

** -> Potencia


*/

let num1 = 20; 
let num2 = 10; 

// + ADIÇÃO 
console.log(num1 + num2);

// Concatenação
let num5 = 10;
let num6 = '5';
console.log(num5 + num6);

// - Subtração
console.log(num1 - num2);

// Divisão 
console.log(num1 / num2);

// Multiplicação
console.log(num1 * num2);


// Resto da divisão
let num3 = 10;
let num4 = 2;
console.log(num3 % num4);

// Potencia 
console.log(num3 ** num4);







